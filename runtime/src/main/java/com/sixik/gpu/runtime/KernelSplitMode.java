package com.sixik.gpu.runtime;

/**
 * Когда рантайм исполняет ядро по стадиям {@code KernelSplitter} (kernel fission, REWORK_ARCHITECTURE.md, 7.1).
 *
 * <p>Разделённое ядро - несколько запусков подряд с тем же NDRange; значения, живые на границе стадий, передаются через
 * промежуточные буферы в global-памяти, которые рантайм выделяет сам. Это снижает давление на регистры стадии, но
 * добавляет запись и чтение промежуточных данных и лишние запуски. Для пользователя вызов не меняется.</p>
 *
 * <p>Замер на RTX 5070 ({@code SplitLaunchDeviceTest}): ядро, проливающее 800 байт регистров, целиком - 0.10-0.13 мс,
 * девятью стадиями без проливания - 0.31-0.53 мс; ядра без проливания стадиями в 3-4 раза медленнее. Проливание в
 * local-память кэшируется L1 и дешевле промежуточных буферов в global-памяти, поэтому по умолчанию деление выключено.</p>
 */
public enum KernelSplitMode {
    /** Не делить ядра. По умолчанию. */
    OFF,
    /**
     * Выбирать по замеру. Кандидат - ядро, которое по данным драйвера проливает регистры в память
     * ({@link DriverStats#spills()}; без статистики драйвера - оценка давления выше бюджета
     * {@code OptimizeOptions.registerBudget()}), если стадии проливают меньше. Первые
     * {@code GpuContext.SPLIT_TRIAL_LAUNCHES} запусков кандидата поочерёдно идут целиком и по стадиям с ожиданием
     * каждого, затем остаётся вариант, который быстрее (стадии - только если быстрее больше чем на 5%).
     */
    AUTO,
    /** Делить всегда, когда {@code KernelSplitter} может разделить ядро (для проверки и замеров). */
    ALWAYS
}
