package com.sixik.gpu.runtime.device;

/**
 * Владелец памяти хоста ({@link HostMemory}): вся память арены освобождается её {@link #close()}. Виды соответствуют
 * аренам FFM, но не требуют его: бэкенд Java 17 реализует их своим выделением памяти.
 */
public interface HostArena extends AutoCloseable {

    /** Вид арены. */
    enum Kind {
        /** Память одного потока; закрытие дешёвое. */
        CONFINED,
        /** Память доступна любому потоку; закрытие может стоить дороже. */
        SHARED,
        /** Память освобождает сборщик мусора, когда на неё не осталось ссылок; {@link #close()} ничего не делает. */
        AUTO
    }

    /**
     * Выделяет память; содержимое новой памяти - нули.
     *
     * @param bytes     размер в байтах ({@code >= 0})
     * @param alignment выравнивание адреса (степень двойки)
     * @return память арены
     */
    HostMemory allocate(long bytes, long alignment);

    /**
     * Привязывает чужую память (например, отображение закреплённого буфера драйвера) к сроку жизни этой арены: после
     * {@link #close()} обращения к возвращённому виду бросают {@link IllegalStateException}. Саму память арена не
     * освобождает.
     *
     * @param memory чужая память
     * @return вид на ту же память, действительный до закрытия арены
     */
    HostMemory attach(HostMemory memory);

    /** Освобождает память арены; повторный вызов безопасен. */
    @Override
    void close();
}
